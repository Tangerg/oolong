//go:build ignore

package main

import (
	"bytes"
	"fmt"
	"go/format"
	"os"
	"strconv"
	"strings"
	"unicode/utf8"
)

const source = "testdata/emoji-variation-sequences.txt"

func main() {
	if err := generate(); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func generate() error {
	data, err := os.ReadFile(source)
	if err != nil {
		return err
	}
	ranges, err := presentationRanges(string(data))
	if err != nil {
		return err
	}
	var output bytes.Buffer
	output.WriteString("// Code generated by go run gen_emoji.go; DO NOT EDIT.\n")
	output.WriteString("// Derived from " + source + "; see UNICODE_LICENSE.\n\n")
	output.WriteString("package grid\n\nimport \"unicode\"\n\n")
	output.WriteString("var emojiPresentationBases = &unicode.RangeTable{\n")
	for _, width := range []int{16, 32} {
		fmt.Fprintf(&output, "R%d: []unicode.Range%d{\n", width, width)
		for _, span := range ranges {
			if (span.last <= 0xffff) != (width == 16) {
				continue
			}
			fmt.Fprintf(&output, "{Lo: %#x, Hi: %#x, Stride: 1},\n", span.first, span.last)
		}
		output.WriteString("},\n")
	}
	output.WriteString("}\n")
	formatted, err := format.Source(output.Bytes())
	if err != nil {
		return err
	}
	return os.WriteFile("emoji_table.go", formatted, 0o644)
}

type codepointRange struct{ first, last uint32 }

func presentationRanges(data string) ([]codepointRange, error) {
	var ranges []codepointRange
	for index, line := range strings.Split(data, "\n") {
		value, _, _ := strings.Cut(line, "#")
		fields := strings.Split(value, ";")
		if len(fields) < 2 || strings.TrimSpace(fields[1]) != "emoji style" {
			continue
		}
		sequence := strings.Fields(fields[0])
		if len(sequence) != 2 || sequence[1] != "FE0F" {
			return nil, fmt.Errorf("%s:%d: unexpected emoji variation sequence", source, index+1)
		}
		value64, err := strconv.ParseUint(sequence[0], 16, 32)
		if err != nil || value64 > utf8.MaxRune || !utf8.ValidRune(rune(value64)) {
			return nil, fmt.Errorf("%s:%d: invalid Unicode scalar", source, index+1)
		}
		codepoint := uint32(value64)
		if len(ranges) > 0 {
			last := &ranges[len(ranges)-1]
			if codepoint <= last.last {
				return nil, fmt.Errorf("%s:%d: sequence bases are not strictly ordered", source, index+1)
			}
			if codepoint == last.last+1 {
				last.last = codepoint
				continue
			}
		}
		ranges = append(ranges, codepointRange{first: codepoint, last: codepoint})
	}
	if len(ranges) == 0 {
		return nil, fmt.Errorf("%s: no emoji presentation sequences", source)
	}
	return ranges, nil
}
